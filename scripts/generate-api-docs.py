#!/usr/bin/env python3
"""Generate the human-readable endpoint index from the checked-in OpenAPI schema."""

import argparse
import json
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "frontend/openapi.json"
TARGET = ROOT / "docs/api.md"
METHODS = ("get", "post", "put", "patch", "delete")


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def render(schema: dict) -> str:
    groups: dict[str, list[tuple[str, str, dict]]] = defaultdict(list)
    for path, path_item in schema["paths"].items():
        for method in METHODS:
            if method in path_item:
                operation = path_item[method]
                groups[(operation.get("tags") or ["other"])[0]].append(
                    (method.upper(), path, operation)
                )

    count = sum(map(len, groups.values()))
    lines = [
        "# API reference",
        "",
        "<!-- Generated by scripts/generate-api-docs.py from frontend/openapi.json. Do not edit by hand. -->",
        "",
        f"OpenAPI {schema['openapi']} · {schema['info']['title']} {schema['info']['version']} · {count} operations.",
        "",
        "All paths are relative to the public site origin. `Bearer` means an access JWT in",
        "`Authorization: Bearer <token>`. Auth endpoints that use the refresh cookie and CSRF",
        "header are marked `Cookie` when OpenAPI declares the refresh cookie. For",
        "`/api/auth/refresh` and `/api/auth/logout`, send the `csrf_token` cookie value",
        "in the `x-csrf-token` header as well (the CSRF dependency is not in OpenAPI).",
        "The [OpenAPI source](../frontend/openapi.json) contains request and response schemas,",
        "examples, constraints, and status codes. In a running backend, `/docs` provides the",
        "interactive Swagger UI.",
        "",
    ]
    for tag, operations in sorted(groups.items()):
        lines.extend(
            [
                f"## {tag.replace('-', ' ').title()}",
                "",
                "| Method | Path | Operation | Auth | Responses |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
        for method, path, operation in sorted(operations, key=lambda row: (row[1], row[0])):
            parameters = operation.get("parameters", [])
            auth = "Bearer" if operation.get("security") else "Public"
            if any(p.get("in") == "cookie" for p in parameters):
                auth = "Cookie"
            responses = ", ".join(sorted(operation.get("responses", {})))
            summary = operation.get("summary") or operation.get("operationId", "")
            lines.append(
                f"| `{method}` | `{cell(path)}` | {cell(summary)} | {auth} | {responses} |"
            )
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/api.md is stale")
    args = parser.parse_args()
    content = render(json.loads(SOURCE.read_text()))
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            print(f"{TARGET.relative_to(ROOT)} is stale; run python3 scripts/generate-api-docs.py")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is current")
        return 0
    TARGET.write_text(content)
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
